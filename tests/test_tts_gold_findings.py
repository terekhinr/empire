def test_lexicon_keeps_sentence_capital():
    """«Один» в начале предложения не становится строчным «од+ин»."""
    out = RuTtsPipeline.__new__(RuTtsPipeline).speech_text("Один был должен.")
    assert out.startswith("Од+ин"), out


@pytest.fixture(scope="module")
def pipe():
    return RuTtsPipeline.__new__(RuTtsPipeline)


@pytest.mark.parametrize("gid,text,must,must_not", CASES, ids=[c[0] for c in CASES])
def test_gold_finding(pipe, gid, text, must, must_not):
    out = pipe.speech_text(text)
    low = out.casefold()
    for s in must:
        assert s.casefold() in low, f"{gid}: нет «{s}» в: {out}"
    for s in must_not:
        assert s.casefold() not in low, f"{gid}: лишнее «{s}» в: {out}"
