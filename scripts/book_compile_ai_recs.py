#!/usr/bin/env python3
"""Компиляция НПН по консенсусу: Qwen + Яндекс + GigaChat + Gemini + свои правила.

Делаем только то, что повторяется у нескольких рецензентов и безопасно
без выдумывания фактов/образов. Спорное — в блок «Отложено автору».
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SRC = ROOT / "data" / "book" / "НА_ПЕНСИЮ_НИКОГДА_v60_ЧЕРНОВИК.md"
DEFAULT_OUT = (
    ROOT
    / "data"
    / "book"
    / "НА_ПЕНСИЮ_НИКОГДА_компиляция_по_рекомендациям_ИИ.md"
)

AUTHOR_LATER = """
---

## Отложено автору (консенсус рецензий — решить вручную)

Эти пункты повторяются у Яндекса / GigaChat / Gemini / Qwen, но требуют твоей крови
или ломают структуру. ИИ их не закрывает.

1. **Хронология рассказчика.** Жёстко зафиксировать возраст/стаж в одной шкале
   (сейчас 48 / «тогда 43» / 22 года переездов — ок как прошлое, но сверить все даты).
2. **Личный факап.** В гл. 9 (или рядом) — один стыдный провал с цифрой. Без этого
   доверие слабее спокойных побед. Пишется только тобой.
3. **Пустые вставки** (`АВТОРСКАЯ ВСТАВКА`) — ночная трасса 72 часа, прозрачность в паре
   и т.п. Не заполнять чужим текстом.
4. **Глава 10 — таблица.** Сухое сравнение: квартира vs коммерция vs ЗПИФ
   (налог, коммуналка, простой, чистая доходность). Публицистику оставить, добавить цифры.
5. **Объём.** GigaChat: после гл. 15 — во вторую книгу / PDF. Резать только после твоего «ок».
6. **Артём / Артифициал.** Gemini критический: убрать картон Кийосаки. Канон сейчас —
   только пролог + гл. 22. Решение: оставить / сжать / заменить на «Первый/Второй».
7. **Пафос-лейблы.** «Манифест / доктрина / Протокол Искусного» — спорно. Голос книги
   на них держится; не выжигать автозаменой.
8. **Актуализация 2026–27.** Точечно ставка/ИИС/налоги — фактчек по реестру чисел
   отдельным проходом (не в этой компиляции).
9. **Qwen «не X, а Y».** Много ложных срабатываний на живой ритм. Править точечно глазами,
   не пачкой.

Что уже сделано в этой компиляции: маркеры ⚔️/✍️ сняты; «мне повезло» переписано
через расчёт; «подачка» смягчена; паразиты «просто/давай разберём» в явных местах;
таймлайн «мне тогда было сорок три»; пустые вставки оставлены как заглушки.
"""


def _apply_consensus(text: str) -> str:
    # --- Маркеры кухни (все рецензенты) ---
    text = re.sub(r"^>\s*⚔️\s*", "> ", text, flags=re.M)
    text = re.sub(r"^⚔️\s*", "", text, flags=re.M)
    text = re.sub(r"\*\*✍️\s*", "**", text)
    text = re.sub(r"\*✍️\s*", "*", text)
    text = re.sub(r"^✍️\s*", "", text, flags=re.M)
    text = re.sub(r">\s*⚔️\s*", "> ", text)

    # --- Самоуничижение в прологе (GigaChat + Gemini, сильный консенсус) ---
    text = text.replace(
        "Компенсацию. Я взял.\n\n"
        "И тут меня можно поймать за руку. Всю книгу я ругаю государство — "
        "а сам-то поднялся на его деньги. Компенсация за службу, потом ипотека "
        "под шесть процентов вместо рыночных двадцати — это всё его рука, его подачка. "
        "Так вот: противоречия здесь нет, и выкручиваться я не стану.",
        "Компенсацию. Я взял.\n\n"
        "И тут меня можно поймать за руку. Всю книгу я ругаю государство — "
        "а сам-то поднялся на его деньги. Компенсация за службу, потом ипотека "
        "под шесть процентов вместо рыночных двадцати — это законные выплаты и льготы "
        "по правилам системы. Я взял положенное и пустил в дело. "
        "Противоречия здесь нет, и выкручиваться я не стану.",
    )
    text = text.replace(
        "И сразу оговорюсь, чтобы никого не ввести в заблуждение. "
        "Мне повезло поймать момент, которого сейчас уже нет.\n\n"
        "Смотри, как сходилась математика тогда.",
        "И сразу оговорюсь, чтобы никого не ввести в заблуждение. "
        "Рынок и льготная ставка дали окно: я использовал ликвидность и насмотренность. "
        "Этого окна сейчас уже нет.\n\n"
        "Смотри, как сходились цифры тогда.",
    )

    # --- Таймлайн: явный «тогда» (GigaChat) ---
    text = text.replace(
        "Так, отложено по мелочи, без всякого плана. Мне сорок три.",
        "Так, отложено по мелочи, без всякого плана. Мне тогда было сорок три.",
    )

    # --- Стоп-фразы «давай разберём» (GigaChat) ---
    text = text.replace(
        "Давай разберём эту иллюзию по пунктам.",
        "Разберём эту иллюзию по пунктам.",
    )
    text = text.replace(
        "давай разберёмся, где в недвижимости на самом деле живут деньги.",
        "разберёмся, где в недвижимости живут деньги.",
    )

    # --- Паразиты «просто» — только явные (Qwen + стоп-лист; кавычки-мантры не трогаем) ---
    replacements = (
        ("просто вопроса не услышал", "вопроса не услышал"),
        ("работает всё до обидного просто:", "работает всё до обидного прямо:"),
        ("Просто все они — пассажиры", "Все они — пассажиры"),
        ("оно просто есть", "оно есть"),
        ("Просто нажав кнопку", "Нажав кнопку"),
        ("Тело не просто терпит нагрузку", "Тело не только терпит нагрузку"),
        ("даёт не просто деньги", "даёт не только деньги"),
        ("Не просто зарплата за труд", "Не одна зарплата за труд"),
        ("— просто лёжа в сейфе", "— лёжа в сейфе"),
        ("Промолчал — просто потерял деньги", "Промолчал — потерял деньги"),
        ("вся тысяча просто кидала монетку", "вся тысяча кидала монетку"),
        ("сперва, как советуют, просто быстро ходить", "сперва, как советуют, быстро ходить"),
        ("Ради одной простой вещи", "Ради одной вещи"),
        ("по одной простой причине", "по одной причине"),
        ("Принцип тут простой:", "Принцип такой:"),
        ("Способ простой.", "Способ такой."),
        ("Правило простое:", "Правило такое:"),
        ("Принцип простой.", "Принцип такой."),
        ("Вывод простой и неожиданный", "Вывод неожиданный"),
        ("Отсюда простой вывод", "Отсюда вывод"),
        ("Смысл лестницы простой:", "Смысл лестницы такой:"),
        ("правило этой главы простое:", "правило этой главы такое:"),
        ("один простой фильтр", "один фильтр"),
        ("простой детектор шарлатана", "детектор шарлатана"),
        ("одну простую вещь", "одну вещь"),
        ("Есть простой приём", "Есть приём"),
        ("И запомни простую вещь", "И запомни"),
        ("Три простых правила", "Три правила"),
        ("Проверить просто.", "Проверить легко."),
        ("оставались бы просто привычками", "оставались бы привычками"),
        ("на самом деле время есть", "время есть"),
        ("**3.4. Почему «просто подождать» не работает**", "**3.4. Почему «подождать» не работает**"),
        # вы → ты (Qwen гл.8; осторожно)
        ("вы выставляли напоказ", "ты выставлял напоказ"),
        ("Вы выставляли напоказ", "Ты выставлял напоказ"),
    )
    for old, new in replacements:
        text = text.replace(old, new)

    # Шапка версии
    text = re.sub(
        r"\*Черновик v60[^\n]*\*",
        "*Компиляция по рекомендациям ИИ — v60 + консенсус Qwen/Яндекс/GigaChat/Gemini*",
        text,
        count=1,
    )
    if "Компиляция по рекомендациям ИИ" not in text[:500]:
        # если шапки v60 не было — вставим после первого заголовка
        lines = text.splitlines()
        for i, ln in enumerate(lines[:30]):
            if ln.startswith("# "):
                lines.insert(
                    i + 1,
                    "\n*Компиляция по рекомендациям ИИ — v60 + консенсус Qwen/Яндекс/GigaChat/Gemini*\n",
                )
                break
        text = "\n".join(lines)

    # Убрать двойные пробелы после вырезок
    text = re.sub(r"  +", " ", text)
    text = re.sub(r" +\n", "\n", text)
    text = re.sub(r"\n{4,}", "\n\n\n", text)

    if "Отложено автору" not in text:
        text = text.rstrip() + "\n" + AUTHOR_LATER

    return text.strip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("-o", "--output", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    raw = args.src.read_text(encoding="utf-8")
    out = _apply_consensus(raw)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(out, encoding="utf-8")
    also = ROOT / "data" / args.output.name
    if also != args.output:
        also.write_text(out, encoding="utf-8")

    print(f"Src:  {args.src} ({len(raw):,} chars)")
    print(f"Out:  {args.output} ({len(out):,} chars)")
    print(f"Copy: {also}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
